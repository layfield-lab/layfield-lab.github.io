"""Build the Layfield Lab site: wraps each page body in the shared header and footer.

Edit the page bodies in pages/*.html and the glossary in pages/glossary.json, then run:
    python3 build.py
The glossary page and the hover definitions (assets/glossary-tips.js) are generated from
pages/glossary.json.
"""
import json
from html import escape
from pathlib import Path

ROOT = Path(__file__).parent
NAV = [
    ("index.html", "Home"),
    ("research.html", "Research"),
    ("software.html", "Software"),
    ("publications.html", "Publications"),
    ("join.html", "Join the lab"),
]
TITLES = {
    "index.html": "Layfield Lab · Computational Chemistry",
    "research.html": "Research · Layfield Lab",
    "software.html": "Software · Layfield Lab",
    "publications.html": "Publications · Layfield Lab",
    "join.html": "Join the lab · Layfield Lab",
    "glossary.html": "Glossary · Layfield Lab",
}
DESCRIPTION = (
    "The Layfield Lab at the University of St. Thomas uses computational chemistry "
    "(quantum chemistry, molecular dynamics and enhanced sampling) with undergraduate researchers."
)
DRAFT = (ROOT / "DRAFT").exists()


def page(name: str, body: str) -> str:
    current = ' aria-current="page"'
    nav = "\n".join(
        f'        <a href="{href}"{current if href == name else ""}>{label}</a>'
        for href, label in NAV
    )
    banner = (
        '<div class="draft-banner">Draft for review. Not yet published.</div>\n' if DRAFT else ""
    )
    return f"""<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>{TITLES[name]}</title>
  <meta name="description" content="{DESCRIPTION}">
  <link rel="stylesheet" href="assets/site.css">
  <script src="assets/glossary-tips.js" defer></script>
  <script src="assets/glossary.js" defer></script>
</head>
<body>
{banner}<header class="site-header">
    <div class="wrap">
      <a class="brand" href="index.html"><strong>Layfield Lab</strong><span>Computational chemistry · University of St. Thomas</span></a>
      <nav class="nav" aria-label="Main">
{nav}
      </nav>
    </div>
  </header>
  <main>
{body}
  </main>
  <footer class="site-footer">
    <div class="wrap">
      <div>Layfield Lab, Department of Chemistry, University of St. Thomas, St. Paul, Minnesota</div>
      <div><a href="mailto:jlayfield@stthomas.edu">jlayfield@stthomas.edu</a> · <a href="https://github.com/layfield-lab">GitHub</a></div>
    </div>
  </footer>
</body>
</html>
"""


def glossary_body(data: dict) -> str:
    """Glossary page body: a jump list, then one entry per term, grouped."""
    jump = " · ".join(
        f'<a href="#{t["id"]}">{escape(t["term"].split(" (")[0])}</a>'
        for g in data["groups"] for t in g["terms"]
    )
    parts = [f"""    <section class="page-head">
      <div class="wrap">
        <div class="eyebrow">Glossary</div>
        <h1>Methods and tools, explained</h1>
        <p class="lead">Short explanations of the methods and software named on the <a href="research.html">research page</a>. On that page, hover over or tab to a method for a one-line definition.</p>
        <p class="glossary-jump small">{jump}</p>
      </div>
    </section>
    <div class="wrap glossary">"""]
    for g in data["groups"]:
        parts.append(f'      <h2 class="glossary-group">{escape(g["title"])}</h2>')
        for t in g["terms"]:
            paras = "\n".join(f"          <p>{para}</p>" for para in t["long"])
            used = ", ".join(f'<a href="{h}">{escape(lbl)}</a>' for lbl, h in t["used_in"])
            learn = "".join(f'<li><a href="{u}">{escape(lbl)}</a></li>' for lbl, u in t["learn"])
            meta = f'<p class="small muted">Used in: {used}</p>' if used else ""
            more = f'<ul class="glossary-learn small">{learn}</ul>' if learn else ""
            figure = ""
            if image := t.get("figure"):
                src = escape(image["src"], quote=True)
                alt = escape(image["alt"], quote=True)
                caption = escape(image["caption"])
                figure = f'''
        <figure class="glossary-figure">
          <a href="{src}" aria-label="View larger illustration: {escape(t['term'], quote=True)}"><img src="{src}" alt="{alt}" loading="lazy" decoding="async" width="{image['width']}" height="{image['height']}"></a>
          <figcaption>{caption} <a href="{src}">View larger image</a></figcaption>
        </figure>'''
            parts.append(f"""      <article class="glossary-entry" id="{t['id']}">
        <h3>{escape(t['term'])}</h3>
        <p class="glossary-short">{escape(t['short'])}</p>
{paras}{figure}
        {meta}{more}
      </article>""")
    parts.append("    </div>")
    return "\n".join(parts)


def tips_js(data: dict) -> str:
    tips = {t["id"]: {"term": t["term"], "short": t["short"]} for g in data["groups"] for t in g["terms"]}
    return ("// Generated by build.py from pages/glossary.json. Do not edit by hand.\n"
            "window.GLOSSARY_TIPS = " + json.dumps(tips, ensure_ascii=False, indent=1) + ";\n")


for href, _ in NAV:
    body = (ROOT / "pages" / href).read_text()
    (ROOT / href).write_text(page(href, body))
    print("built", href)

glossary = json.loads((ROOT / "pages" / "glossary.json").read_text())
(ROOT / "glossary.html").write_text(page("glossary.html", glossary_body(glossary)))
(ROOT / "assets" / "glossary-tips.js").write_text(tips_js(glossary))
print("built glossary.html and assets/glossary-tips.js")
